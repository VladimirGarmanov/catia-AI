"""Read numeric CATIA SAFEARRAY outputs without losing their by-reference value.

pywin32's generated/type-informed methods may declare a SAFEARRAY parameter as
input-only. Passing a VARIANT to that wrapper raises "Objects for SAFEARRAYS
must be sequences"; passing a list can silently discard CATIA's output. Invoke
the same bound IDispatch member with explicit VARIANT marshaling instead. This
is the untyped call path used by pywin32's DumbDispatch, without probing the
member as a property first. No makepy cache changes, scripts or retries occur.
"""
import math

from catia_mcp.runtime import CADOperationError


def read_array(method, count, *inputs):
    try:
        import pythoncom
        from win32com.client import VARIANT
    except ImportError as exc:
        raise CADOperationError("CAPABILITY_UNAVAILABLE", "SAFEARRAY adapter requires Windows pywin32") from exc
    method_name = getattr(method, "__name__", None)
    owner = getattr(method, "__self__", None)
    dispatch = getattr(owner, "_oleobj_", None) if owner is not None else None
    call_path = "callable"
    try:
        output = VARIANT(pythoncom.VT_BYREF | pythoncom.VT_ARRAY | pythoncom.VT_VARIANT,
                         tuple(float("nan") for _ in range(count)))
        if dispatch is not None and isinstance(method_name, str):
            # InvokeTypes (including wrappers generated by dynamic.Dispatch)
            # imposes its array descriptor before examining our VARIANT. Invoke
            # instead lets PythonOleArgHelper preserve its explicit BYREF type
            # and copy the output SAFEARRAY back to output.value after the call.
            # Resolve the DISPID from this exact object, never hard-code an ID.
            call_path = "IDispatch.Invoke"
            dispid = dispatch.GetIDsOfNames(0, method_name)
            returned = dispatch.Invoke(dispid, 0, pythoncom.DISPATCH_METHOD, True,
                                       *inputs, output)
        else:
            # Plain Python adapters/test doubles have no IDispatch to unwrap.
            returned = method(*inputs, output)
        values = output.value
        if returned is not None and isinstance(returned, (tuple, list)) and len(returned) == count:
            values = returned
        result = [float(value) for value in values]
        if len(result) != count or not all(math.isfinite(value) for value in result):
            raise ValueError("Output array was not populated with finite values")
        return result
    except Exception as exc:
        raise CADOperationError(
            "CAPABILITY_UNAVAILABLE",
            f"CATIA SAFEARRAY read failed ({method_name or 'reader'}, {call_path}, "
            f"{type(exc).__name__}): {exc}",
        ) from exc
